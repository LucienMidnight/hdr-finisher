/* Library selection reaches Export: menu availability, Open in Export and Quick export. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '..'), output = path.join(root, 'output', 'library-export-menu');
fs.mkdirSync(output, {recursive:true});
const folder = fs.mkdtempSync(path.join(output, 'photos-'));
const photos = ['one.png','two.png','three.png'].map(name => path.join(folder,name));
for (const photo of photos) fs.copyFileSync(path.join(root,'tests','fixtures','sdr_gradient.png'),photo);
(async () => {
  const browser = await chromium.launch({headless:true,channel:'msedge'});
  try {
    const page = await browser.newPage(), errors=[];
    page.on('pageerror', error=>errors.push(error.message)); page.setDefaultTimeout(30000);
    await page.goto(process.env.HDR_FINISHER_URL,{waitUntil:'networkidle'});
    await page.evaluate(()=>activateWorkflowTab('import'));
    // A Grade picture that finishes loading behind the Library must stay hidden (it floated over the grid, October 18).
    assert.equal(await page.evaluate(()=>{const image=document.getElementById('preview-image');image.dispatchEvent(new Event('load'));return getComputedStyle(image).visibility;}),'hidden');
    const iframe=page.locator('#library-frame'), frame=page.frameLocator('#library-frame');
    await iframe.evaluate((el,folder)=>el.contentWindow.HDRLibrary.browse(folder),folder);
    const cells=frame.locator('.library-cell');
    await page.waitForFunction(()=>document.getElementById('library-frame').contentDocument.querySelectorAll('.library-cell').length===3);
    const other=fs.mkdtempSync(path.join(output,'other-'));
    fs.copyFileSync(photos[0],path.join(other,'other.png'));
    const library=page.frame({url:/\/library(?:\?|$)/});
    const post=(route,body)=>library.evaluate(async({route,body})=>{const r=await fetch('/api/library/'+route,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});if(!r.ok)throw new Error(await r.text());return r.json();},{route,body});
    await post('pins',{paths:[folder,other]});
    await post('albums/create',{name:'Sort album',paths:photos});
    await post('smart-albums',{action:'create',name:'Sort smart',filters:{rules:[{field:'rating',op:'is',value:0}]}});
    await library.goto(new URL('/library',page.url()).href);
    await library.waitForFunction(()=>window.HDRLibrary);
    await library.evaluate(folder=>HDRLibrary.browse(folder),folder);
    const sort=async(field,descending)=>{
      await library.evaluate(({field,descending})=>{
        document.querySelector(`[data-sort="${field}"]`).click();
        if(HDRLibrary.getSnapshot().descending!==descending)document.getElementById('sort-dir').click();
      },{field,descending});
    };
    await sort('name',true);
    const child=path.join(folder,'inside');fs.mkdirSync(child);fs.copyFileSync(photos[0],path.join(child,'nested.png'));
    await library.evaluate(folder=>HDRLibrary.browse(folder),child);
    assert.deepEqual(await library.evaluate(()=>{const s=HDRLibrary.getSnapshot();return [s.sort,s.descending];}),['name',true],'subfolder shares its pinned parent sort');
    fs.unlinkSync(path.join(child,'nested.png'));fs.rmdirSync(child);
    await library.evaluate(folder=>HDRLibrary.browse(folder),other);
    assert.equal((await library.evaluate(()=>HDRLibrary.getSnapshot())).sort,'time');
    await sort('rating',false);
    await library.evaluate(folder=>HDRLibrary.browse(folder),folder);
    assert.deepEqual(await library.evaluate(()=>{const s=HDRLibrary.getSnapshot();return [s.sort,s.descending];}),['name',true]);
    await library.evaluate(folder=>HDRLibrary.browse(folder),other);
    assert.equal((await library.evaluate(()=>HDRLibrary.getSnapshot())).sort,'rating');
    await library.evaluate(folder=>HDRLibrary.browse(folder),folder);
    const snapshot=()=>library.evaluate(()=>{const s=HDRLibrary.getSnapshot();return [s.sort,s.descending];});
    const album=library.locator('#albums').getByRole('button',{name:'Sort album',exact:true});
    const smart=library.locator('#smart-albums').getByRole('button',{name:'Sort smart',exact:true});
    await album.click();assert.deepEqual(await snapshot(),['time',false]);await sort('rating',true);
    await smart.click();assert.deepEqual(await snapshot(),['time',false]);await sort('name',false);
    await album.click();assert.deepEqual(await snapshot(),['rating',true]);
    await smart.click();assert.deepEqual(await snapshot(),['name',false]);
    await library.goto(new URL('/library',page.url()).href);
    await library.waitForFunction(()=>window.HDRLibrary);
    await library.evaluate(folder=>HDRLibrary.browse(folder),folder);
    assert.deepEqual(await snapshot(),['name',true],'folder sort survives reload');
    await album.click();assert.deepEqual(await snapshot(),['rating',true]);
    await smart.click();assert.deepEqual(await snapshot(),['name',false]);
    await library.evaluate(folder=>HDRLibrary.browse(folder),folder);
    const menu=page.locator('[data-desktop-command="quick-export"]');
    await cells.first().click();
    await page.waitForFunction(()=>!document.querySelector('[data-desktop-command="quick-export"]').disabled);
    await frame.locator('#library-grid').press('Control+a');
    await page.waitForTimeout(300);
    const afterAll=await menu.isDisabled();
    const selected=await iframe.evaluate(el=>el.contentWindow.HDRLibraryCommands.selection().length);
    console.log(JSON.stringify({afterSelectAllDisabled:afterAll,selected}));
    assert.equal(selected,3);assert.equal(afterAll,false,'menu after Ctrl+A');
    await cells.first().click({button:'right'});
    await frame.getByRole('menuitem',{name:'Open in Export',exact:true}).click();
    await page.waitForFunction(()=>document.body.dataset.workflow==='export');
    await page.waitForFunction(()=>document.querySelectorAll('.batch-photo').length===3);
    await page.locator('#batch-grid-panel').getByRole('button',{name:'Select all',exact:true}).click();
    assert.equal(await page.locator('.batch-photo[aria-selected="true"]').count(),3);
    assert.equal(await page.locator('#batch-run').isVisible(),true);
    assert.ok(await page.locator('#export-format option').count()>0,'format choices without a Grade photo');
    await page.screenshot({path:path.join(output,'export-from-library.png')});
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({menuEnabled:true,openInExport:3,selectAll:3}));
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
