const assert = require('node:assert/strict');
module.exports = async function checkStockCharacterUi(page) {
 const result = await page.evaluate(async () => {
  const check = (value, label) => { if (!value) throw Error(label); };
  const original = structuredClone(state.adjustments);
  const hdr = () => state.adjustments.hdr.film_look;
  const input = (key, value) => {
   const control=document.querySelector(`[data-path="current.film_look.${key}"]`);
   check(control,`missing ${key}`); control.value=String(value);
   control.dispatchEvent(new Event('input',{bubbles:true}));
  };
  const dot = key => document.querySelector(`[data-stock-reset="${key}"]`);
  await switchLane('hdr');
  state.adjustments.hdr.film_look=defaultFilmLook(); syncControlsFromState(); renderControlState();
  input('film_stock','kodak_portra_400'); await syncGlobalEditState();
  check(hdr().grain_amount===HDRFilmCharacterData.portra_400_anchor_amount && hdr().halation_amount>0,'stock did not set own effects');
  check(document.querySelector('[data-value-path="current.film_look.halation_amount"]').textContent==='100% stock','relative readout');
  check(Math.abs(Number(document.querySelector('#film-halation-hue').value))<1e-6,'hue does not display zero');
  input('grain_amount',HDRFilmCharacterData.portra_400_anchor_amount); await syncGlobalEditState();
  check(hdr().stock_overrides.includes('grain_amount') && !dot('grain_amount').hidden,'equal value does not become set');
  input('film_stock','kodak_vision3_500t'); await syncGlobalEditState();
  check(hdr().grain_amount===HDRFilmCharacterData.portra_400_anchor_amount && hdr().grain_size===HDRFilmCharacterData.stocks.kodak_vision3_500t.defaults.grain_size,'stock overwrote set control');
  dot('grain_amount').click(); await syncGlobalEditState();
  check(!hdr().stock_overrides.includes('grain_amount') && dot('grain_amount').hidden,'dot reset did not restore inheritance');
  input('print_paper','fujifilm_crystal_archive_typeii'); await syncGlobalEditState();
  check(!dot('print_paper').hidden,'paper dot missing');
  dot('print_paper').click(); await syncGlobalEditState(); check(hdr().print_paper==='default','paper dot did not reset');
  input('halation_amount',50); await syncGlobalEditState();
  check(Math.abs(hdr().halation_amount-HDRFilmCharacterData.stocks.kodak_vision3_500t.defaults.halation_amount*.5)<1e-6,'relative amount input conversion');
  dot('halation_amount').click(); await syncGlobalEditState();
  const inherited=hdr().grain_amount;
  input('grain_amount',73); await syncGlobalEditState();
  await queueEditCommand('undo');
  check(hdr().grain_amount===inherited && !hdr().stock_overrides.includes('grain_amount'),'undo ownership/value');
  await queueEditCommand('redo');
  check(hdr().grain_amount===73 && hdr().stock_overrides.includes('grain_amount'),'redo ownership/value');
  await switchLane('sdr'); matchHdrFilmLookToSdr(); await syncGlobalEditState();
  check(JSON.stringify(state.adjustments.sdr.film_look)===JSON.stringify(hdr()),'Match HDR did not copy ownership');
  input('grain_amount',31); await syncGlobalEditState(); check(hdr().grain_amount===73,'SDR shares HDR state');
  input('print_paper','kodak_2383'); await syncGlobalEditState();
  input('film_stock','fujifilm_velvia_100'); await syncGlobalEditState();
  check(!dot('print_paper').disabled,'slide must allow inherited-paper reset');
  dot('print_paper').click(); await syncGlobalEditState(); check(state.adjustments.sdr.film_look.print_paper==='default','slide paper reset');
  const grain=document.querySelector('#film-grain-amount');
  grain.dispatchEvent(new MouseEvent('dblclick',{bubbles:true})); await syncGlobalEditState();
  check(!state.adjustments.sdr.film_look.stock_overrides.includes('grain_amount'),'double-click must restore inheritance');
  const typed=normalizeManualControlValue('current.film_look.halation_radius','150');
  commitAdjustmentValue('current.film_look.halation_radius',typed.value,{manual:true}); await syncGlobalEditState();
  check(Math.abs(state.adjustments.sdr.film_look.halation_radius-HDRFilmCharacterData.stocks.fujifilm_velvia_100.defaults.halation_radius*1.5)<1e-6,'typed relative spread');
  state.adjustments=original; syncControlsFromState(); invalidatePreview('hdr'); invalidatePreview('sdr'); await syncGlobalEditState();
  return {passed:true};
 });
 assert.equal(result.passed,true);
 console.log('Stock character UI: select, set, dot/paper reset, relative input, undo/redo and independent Match HDR PASS');
};
