const fs = require('node:fs');
const path = require('node:path');
const {readTimings} = require('../tests/release/timings.cjs');
const {select, estimate} = require('../tests/release/runner.cjs');
const ROOT = path.resolve(__dirname,'../..');
const FILE = path.join(ROOT,'docs/technical/test-catalogue.md');
function render(list = require('../tests/release/drivers.json'), timings = readTimings()) {
  const minutes = (row, platform) => timings.drivers[row.path]?.[platform]?.medianSeconds / 60 || row.expectedMinutes[platform];
  const lines = ['# Test catalogue', '', 'Generated by `node codebase/tools/test-catalogue.cjs`. Edit the manifest, committed timings or everyday inventory, then regenerate.', '',
    'Briefs cover registered slow drivers and helpers. Unknown durations are **unknown**, never zero. Timings estimate complete attempts (including failures), not passing certification. Earlier revisions can be much slower than current drivers.', '',
    '## Focused release estimates', '', 'The selection depends on changed areas since the last tag. Core is the smallest selection; all areas is the conservative union. Per-driver rows below show normal single-attempt minutes; totals reserve one retry for recorded failed attempts. Incomplete subtotals are not permission to start a long run.', '',
    '| Selection | Drivers | Windows minutes + retry | Windows unknown | Mac minutes + retry | Mac unknown |', '| --- | ---: | ---: | ---: | ---: | ---: |'];
  for (const [name, changed] of [['Core',[]], ['All areas',['codebase/frontend/unmapped-catalogue-selection.js']], ...list.areas.map(area=>[area,null])]) {
    const rows = changed ? select(list,'release',null,changed).rows : list.drivers.filter(row=>row.launch.method!=='helper' && row.tier!=='diagnostic' && (row.tier==='core' || row.tier==='area' && row.areas.includes(name)));
    const stats = ['win','mac'].map(platform => {
      const records = rows.flatMap(row => {
        const timing=timings.drivers[row.path]?.[platform], duration=minutes(row,platform);
        return duration === null || duration === undefined ? [] : [{driver:row.path,durationSeconds:duration*60,exitCode:timing?.exitCode ?? null}];
      });
      const result=estimate(rows,records);
      return `${(result.seconds/60).toFixed(2)} + ${(result.retrySeconds/60).toFixed(2)} | ${result.unknown.length}`;
    });
    lines.push(`| ${name} | ${rows.length} | ${stats.join(' | ')} |`);
  }
  lines.push('', '## Everyday tests', '', '<!-- everyday-inventory-include -->');
  const inventory=path.join(ROOT,'codebase/tests/inventory.json');
  if (fs.existsSync(inventory)) {
    const data=JSON.parse(fs.readFileSync(inventory,'utf8'));
    lines.push('Source: `codebase/tests/inventory.json`. Seconds are summed case time, not parallel suite wall time. Unknown Mac values remain unknown.', '',
      '| File | Purpose | Cases | Windows seconds | Mac seconds | Requirements / platform skips |', '| --- | --- | ---: | ---: | ---: | --- |');
    const escape=value=>String(value ?? '').replace(/\|/g,'\\|').replace(/[\r\n]+/g,' ');
    for (const row of (data.entries || data.tests || data.files || data.items || []).slice().sort((a,b)=>a.file.localeCompare(b.file))) {
      lines.push(`| ${escape(row.file)} | ${escape(row.purpose)} | ${row.test_count} | ${row.seconds?.windows ?? 'unknown'} | ${row.seconds?.mac ?? 'unknown'} | ${escape([...(row.requirements || []),...(row.platform_notes || row.platform_skips || [])].join('; '))} |`);
    }
  } else lines.push('**Pending include:** `codebase/tests/inventory.json` (everyday-test inventory worker). Regenerate when it arrives.');
  lines.push('', '## Driver briefs', '', 'Drivers with multiple areas appear in each area. Requirements and platform notes come from source recipes, release README, module guidance, the overnight report and performance table. A listed OS is a target, not evidence of a recent pass. Inspect platform branches and missing-fixture skips.', '');
  for (const area of list.areas) for (const tier of ['core','area','full','diagnostic']) {
    const rows=list.drivers.filter(row=>row.areas.includes(area)&&row.tier===tier).sort((a,b)=>a.path.localeCompare(b.path));
    if (!rows.length) continue;
    lines.push(`### ${area} / ${tier}`, '');
    for (const row of rows) {
      lines.push(`#### \`${row.path}\``, '', row.brief, '',
        `- Expected minutes: Windows ${minutes(row,'win')?.toFixed(3) ?? 'unknown'}; Mac ${minutes(row,'mac')?.toFixed(3) ?? 'unknown'}.`,
        `- Unmeasured default deadline: ${row.deadlineMinutes ?? 'parent'} minutes. ${row.deadlinePolicy}`,
        `- Requirements: ${row.requirements.join(' ')}`,
        `- Platforms: ${row.platforms.os.join(', ')}. ${row.platforms.notes.join(' ')}`, '');
    }
  }
  return lines.join('\n')+'\n';
}
function generate() { const text=render(); if (!fs.existsSync(FILE)||fs.readFileSync(FILE,'utf8')!==text) fs.writeFileSync(FILE,text); }
if (require.main===module) generate();
module.exports={render,generate,FILE};
